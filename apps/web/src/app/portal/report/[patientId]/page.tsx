'use client';

import { useEffect, useState } from 'react';
import { useParams, useRouter } from 'next/navigation';
import { api, ReportData } from '@/lib/api';
import { useAuth } from '@/lib/auth-context';
import { Logo, prettyWhen } from '@/components/ui';

export default function ReportPage() {
  const { user } = useAuth();
  const params = useParams<{ patientId: string }>();
  const router = useRouter();
  const [report, setReport] = useState<ReportData | null>(null);
  const [error, setError] = useState('');

  useEffect(() => {
    let cancelled = false;
    (async () => {
      const { ok, data } = await api<ReportData>(`/reports/${params.patientId}`);
      if (cancelled) return;
      if (ok) setReport(data);
      else setError(data.error || 'Could not load report.');
    })();
    return () => {
      cancelled = true;
    };
  }, [params.patientId]);

  if (!user) return null;
  if (error) {
    return (
      <div className="panel">
        <h2>Report</h2>
        <p className="empty">{error}</p>
        <button className="btn btn-ghost btn-sm" onClick={() => router.back()}>
          Back
        </button>
      </div>
    );
  }
  if (!report) return <p className="empty">Loading…</p>;

  return (
    <div className="report">
      <div className="report-actions no-print">
        <button className="btn btn-ghost btn-sm" onClick={() => router.back()}>
          Back
        </button>
        <button className="btn btn-primary btn-sm" onClick={() => window.print()}>
          Print / save as PDF
        </button>
      </div>

      <div className="report-doc">
        <header className="report-head">
          <div className="report-brand">
            <Logo size={30} />
            <span>Zero Health</span>
          </div>
          <h1>Medical Report</h1>
          <div className="report-meta">
            <span>Patient: {report.patient.full_name}</span>
            <span>Patient ID: {report.patient.id}</span>
            <span>Generated: {new Date().toISOString().slice(0, 16).replace('T', ' ')}</span>
          </div>
        </header>

        <section>
          <h2>Appointments</h2>
          {report.appointments.length === 0 ? (
            <p className="muted">No appointments on file.</p>
          ) : (
            <table>
              <thead>
                <tr>
                  <th>When</th>
                  <th>Kind</th>
                  <th>Modality</th>
                  <th>Status</th>
                </tr>
              </thead>
              <tbody>
                {report.appointments.map((a) => (
                  <tr key={a.id}>
                    <td>{prettyWhen(a.scheduled_for)}</td>
                    <td>{a.kind}</td>
                    <td>{a.modality}</td>
                    <td>{a.status}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}
        </section>

        <section>
          <h2>Prescriptions</h2>
          {report.prescriptions.length === 0 ? (
            <p className="muted">No prescriptions on file.</p>
          ) : (
            <table>
              <thead>
                <tr>
                  <th>Medication</th>
                  <th>Dosage</th>
                  <th>Prescriber</th>
                  <th>Status</th>
                </tr>
              </thead>
              <tbody>
                {report.prescriptions.map((p) => (
                  <tr key={p.id}>
                    <td>{p.medication}</td>
                    <td>{p.dosage}</td>
                    <td>{p.prescriber_name || ''}</td>
                    <td>{p.status}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}
        </section>

        <section>
          <h2>Lab results</h2>
          {report.lab_results.length === 0 ? (
            <p className="muted">No lab results on file.</p>
          ) : (
            <table>
              <thead>
                <tr>
                  <th>Panel</th>
                  <th>Value</th>
                  <th>Interpretation</th>
                </tr>
              </thead>
              <tbody>
                {report.lab_results.map((l) => (
                  <tr key={l.id}>
                    <td>{l.panel}</td>
                    <td>{l.value}</td>
                    <td>{l.interpretation || ''}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}
        </section>

        <footer className="report-foot">
          Generated by Zero Health · Demo document
        </footer>
      </div>
    </div>
  );
}
